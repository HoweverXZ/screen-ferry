//! 按键映射：macOS 虚拟键码（`kVK_*`）→ USB HID 键码。
//!
//! 键码是物理位置，与键盘布局、输入法无关。对照表参考 Chromium 的 keycode_converter。

use ferry_types::KeyCode;

/// macOS 虚拟键码对应的 HID 键码。Fn 等没有 HID 对应的键返回 `None`。
pub fn hid_code(keycode: u16) -> Option<KeyCode> {
    let usage = match keycode {
        0x00 => 0x04, // A
        0x01 => 0x16, // S
        0x02 => 0x07, // D
        0x03 => 0x09, // F
        0x04 => 0x0B, // H
        0x05 => 0x0A, // G
        0x06 => 0x1D, // Z
        0x07 => 0x1B, // X
        0x08 => 0x06, // C
        0x09 => 0x19, // V
        0x0A => 0x64, // ISO 键盘的 § 键
        0x0B => 0x05, // B
        0x0C => 0x14, // Q
        0x0D => 0x1A, // W
        0x0E => 0x08, // E
        0x0F => 0x15, // R
        0x10 => 0x1C, // Y
        0x11 => 0x17, // T
        0x12 => 0x1E, // 1
        0x13 => 0x1F, // 2
        0x14 => 0x20, // 3
        0x15 => 0x21, // 4
        0x16 => 0x23, // 6
        0x17 => 0x22, // 5
        0x18 => 0x2E, // =
        0x19 => 0x26, // 9
        0x1A => 0x24, // 7
        0x1B => 0x2D, // -
        0x1C => 0x25, // 8
        0x1D => 0x27, // 0
        0x1E => 0x30, // ]
        0x1F => 0x12, // O
        0x20 => 0x18, // U
        0x21 => 0x2F, // [
        0x22 => 0x0C, // I
        0x23 => 0x13, // P
        0x24 => 0x28, // Return
        0x25 => 0x0F, // L
        0x26 => 0x0D, // J
        0x27 => 0x34, // '
        0x28 => 0x0E, // K
        0x29 => 0x33, // ;
        0x2A => 0x31, // \
        0x2B => 0x36, // ,
        0x2C => 0x38, // /
        0x2D => 0x11, // N
        0x2E => 0x10, // M
        0x2F => 0x37, // .
        0x30 => 0x2B, // Tab
        0x31 => 0x2C, // 空格
        0x32 => 0x35, // `
        0x33 => 0x2A, // Delete（退格）
        0x35 => 0x29, // Esc
        0x36 => 0xE7, // 右 Command
        0x37 => 0xE3, // 左 Command
        0x38 => 0xE1, // 左 Shift
        0x39 => 0x39, // Caps Lock
        0x3A => 0xE2, // 左 Option
        0x3B => 0xE0, // 左 Control
        0x3C => 0xE5, // 右 Shift
        0x3D => 0xE6, // 右 Option
        0x3E => 0xE4, // 右 Control
        0x40 => 0x6C, // F17
        0x41 => 0x63, // 小键盘 .
        0x43 => 0x55, // 小键盘 *
        0x45 => 0x57, // 小键盘 +
        0x47 => 0x53, // 小键盘 Clear，相当于 Num Lock
        0x48 => 0x80, // 音量加
        0x49 => 0x81, // 音量减
        0x4A => 0x7F, // 静音
        0x4B => 0x54, // 小键盘 /
        0x4C => 0x58, // 小键盘 Enter
        0x4E => 0x56, // 小键盘 -
        0x4F => 0x6D, // F18
        0x50 => 0x6E, // F19
        0x51 => 0x67, // 小键盘 =
        0x52 => 0x62, // 小键盘 0
        0x53 => 0x59, // 小键盘 1
        0x54 => 0x5A, // 小键盘 2
        0x55 => 0x5B, // 小键盘 3
        0x56 => 0x5C, // 小键盘 4
        0x57 => 0x5D, // 小键盘 5
        0x58 => 0x5E, // 小键盘 6
        0x59 => 0x5F, // 小键盘 7
        0x5A => 0x6F, // F20
        0x5B => 0x60, // 小键盘 8
        0x5C => 0x61, // 小键盘 9
        0x5D => 0x89, // JIS ¥
        0x5E => 0x87, // JIS _
        0x5F => 0x85, // JIS 小键盘 ,
        0x60 => 0x3E, // F5
        0x61 => 0x3F, // F6
        0x62 => 0x40, // F7
        0x63 => 0x3C, // F3
        0x64 => 0x41, // F8
        0x65 => 0x42, // F9
        0x66 => 0x91, // JIS 英数
        0x67 => 0x44, // F11
        0x68 => 0x90, // JIS かな
        0x69 => 0x68, // F13
        0x6A => 0x6B, // F16
        0x6B => 0x69, // F14
        0x6D => 0x43, // F10
        0x6E => 0x65, // 菜单键
        0x6F => 0x45, // F12
        0x71 => 0x6A, // F15
        0x72 => 0x49, // Help，位置相当于 PC 键盘的 Insert
        0x73 => 0x4A, // Home
        0x74 => 0x4B, // Page Up
        0x75 => 0x4C, // 向前删除
        0x76 => 0x3D, // F4
        0x77 => 0x4D, // End
        0x78 => 0x3B, // F2
        0x79 => 0x4E, // Page Down
        0x7A => 0x3A, // F1
        0x7B => 0x50, // ←
        0x7C => 0x4F, // →
        0x7D => 0x51, // ↓
        0x7E => 0x52, // ↑
        _ => return None,
    };
    Some(KeyCode::keyboard(usage))
}

/// 修饰键在 `CGEventFlags` 中对应的“设备相关”位，用来区分左右键各自的按下与松开。
pub(crate) fn modifier_flag(keycode: u16) -> Option<u64> {
    Some(match keycode {
        0x3B => 0x0000_0001, // 左 Control
        0x38 => 0x0000_0002, // 左 Shift
        0x3C => 0x0000_0004, // 右 Shift
        0x37 => 0x0000_0008, // 左 Command
        0x36 => 0x0000_0010, // 右 Command
        0x3A => 0x0000_0020, // 左 Option
        0x3D => 0x0000_0040, // 右 Option
        0x3E => 0x0000_2000, // 右 Control
        _ => return None,
    })
}

/// 媒体键（`NX_KEYTYPE_*`）对应的 HID 键码。
///
/// 只映射对方系统也有的键：音量和播放控制。亮度、键盘背光等返回 `None`，
/// 它们始终留给本机处理，光标在对方屏幕时也一样。
pub fn media_key(nx_key: u32) -> Option<KeyCode> {
    Some(match nx_key {
        0 => KeyCode::VOLUME_UP,       // NX_KEYTYPE_SOUND_UP
        1 => KeyCode::VOLUME_DOWN,     // NX_KEYTYPE_SOUND_DOWN
        7 => KeyCode::MUTE,            // NX_KEYTYPE_MUTE
        16 => KeyCode::PLAY_PAUSE,     // NX_KEYTYPE_PLAY
        17 => KeyCode::NEXT_TRACK,     // NX_KEYTYPE_NEXT
        18 => KeyCode::PREVIOUS_TRACK, // NX_KEYTYPE_PREVIOUS
        _ => return None,
    })
}
